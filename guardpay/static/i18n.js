  function t(key, params) {
    const dict = translations[currentLang] || translations.en;
    let str = dict[key] || translations.en[key] || key;
    if (params) {
      for (const [k, v] of Object.entries(params)) {
        str = str.split('{' + k + '}').join(String(v));
      }
    }
    return str;
  }

  function setLang(lang) {
    if (lang !== 'en' && lang !== 'am') lang = 'en';
    currentLang = lang;
    try { localStorage.setItem('guardpay-lang', lang); } catch(e) {}
    document.documentElement.lang = lang === 'am' ? 'am' : 'en';
    if (lang === 'am') {
      document.body.style.fontFamily = "'Noto Sans Ethiopic', 'Inter', system-ui, sans-serif";
    } else {
      document.body.style.fontFamily = '';
    }
    refreshAll();
  }

  function initLang() {
    try {
      const saved = localStorage.getItem('guardpay-lang');
      if (saved === 'en' || saved === 'am') currentLang = saved;
    } catch(e) {}
    document.documentElement.lang = currentLang === 'am' ? 'am' : 'en';
    if (currentLang === 'am') {
      document.body.style.fontFamily = "'Noto Sans Ethiopic', 'Inter', system-ui, sans-serif";
    }
  }

  function getLang() { return currentLang; }

  function refreshAll() {
    document.querySelectorAll('[data-i18n]').forEach(el => {
      el.textContent = t(el.dataset.i18n);
    });
    document.querySelectorAll('[data-i18n-html]').forEach(el => {
      el.innerHTML = t(el.dataset.i18nHtml);
    });
    document.querySelectorAll('[data-i18n-placeholder]').forEach(el => {
      el.placeholder = t(el.dataset.i18nPlaceholder);
    });
    document.querySelectorAll('[data-i18n-aria]').forEach(el => {
      el.setAttribute('aria-label', t(el.dataset.i18nAria));
    });
    document.querySelectorAll('[data-i18n-title]').forEach(el => {
      el.title = t(el.dataset.i18nTitle);
    });
  }

  const MONTHS = () => translations[currentLang]?.months_full || translations.en.months_full;
  const MONTHS_SHORT = () => translations[currentLang]?.months_short || translations.en.months_short;

  return { t, setLang, initLang, getLang, refreshAll, MONTHS, MONTHS_SHORT };
